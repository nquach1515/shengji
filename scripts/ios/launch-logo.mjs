// Makes the iOS launch logo from the phone home screen, so the launch screen and the home screen logo match exactly
// (see src/ui/LaunchIntro.tsx). Writes public/launch-logo.png, src/ui/launchLogo.json, the LaunchLogo image asset and
// the launch storyboard. Rerun after changing the home logo:
//   npm run build && npx vite preview --port 4799 &      (then)
//   npm i --no-save playwright-core && npx playwright-core install webkit && node scripts/ios/launch-logo.mjs
import { mkdirSync, writeFileSync } from 'node:fs';
import { webkit } from 'playwright-core';

const URL_ = process.env.HOME_URL ?? 'http://localhost:4799/';
const ROOT = new URL('../../', import.meta.url).pathname;
const K = 1.3; // launch logo size relative to the home screen logo; it shrinks into place
const PAD = 16; // must match LOGO_PAD and LOGO_PAD_BOTTOM in LaunchIntro.tsx
const PAD_BOTTOM = 34;
const BG = [18, 5, 7]; // #120507, LAUNCH_BG

async function capture(scale) {
  const b = await webkit.launch(); // the iOS app renders with WebKit; Chrome measures the title's box a little differently
  const p = await b.newPage({ viewport: { width: 402, height: 874 }, deviceScaleFactor: scale * K, isMobile: true, hasTouch: true });
  await p.goto(URL_);
  await p.waitForTimeout(2500); // fan finished dealing in
  const rect = await p.evaluate(([PAD, PAD_BOTTOM]) => {
    const inner = document.querySelector('.home-inner');
    for (const el of inner.children) if (!el.matches('.logo-fan, .wordmark')) el.style.visibility = 'hidden';
    document.querySelector('.wordmark .en').style.visibility = 'hidden';
    const st = document.createElement('style');
    st.textContent = 'html,body,#root,.stage,.screen,.home{background:transparent!important} .felt{display:none!important}';
    document.head.appendChild(st);
    // same box as logoRect() in LaunchIntro.tsx
    const cards = [...document.querySelectorAll('.logo-fan > div')];
    const cs = cards.map((c) => c.getBoundingClientRect());
    const z = document.querySelector('.wordmark .zh').getBoundingClientRect();
    const left = Math.min(...cs.map((r) => r.left)) - PAD, right = Math.max(...cs.map((r) => r.right)) + PAD;
    const top = Math.min(z.top, ...cs.map((r) => r.top)) - PAD, bottom = Math.max(z.bottom, ...cs.map((r) => r.bottom)) + PAD_BOTTOM;
    return { x: left, y: top, width: right - left, height: bottom - top };
  }, [PAD, PAD_BOTTOM]);
  await p.waitForTimeout(200);
  const png = await p.screenshot({ clip: rect, omitBackground: true });
  await b.close();
  return { png, rect };
}

const at3 = await capture(3);
const at2 = await capture(2);
const w = +(at3.rect.width * K).toFixed(2);
const h = +(at3.rect.height * K).toFixed(2);

writeFileSync(`${ROOT}public/launch-logo.png`, at3.png);
writeFileSync(`${ROOT}src/ui/launchLogo.json`, JSON.stringify({ width: w, height: h }) + '\n');

const asset = `${ROOT}ios/App/App/Assets.xcassets/LaunchLogo.imageset`;
mkdirSync(asset, { recursive: true });
writeFileSync(`${asset}/launch-logo@2x.png`, at2.png);
writeFileSync(`${asset}/launch-logo@3x.png`, at3.png);
writeFileSync(
  `${asset}/Contents.json`,
  JSON.stringify(
    {
      images: [
        { idiom: 'universal', scale: '1x' },
        { idiom: 'universal', filename: 'launch-logo@2x.png', scale: '2x' },
        { idiom: 'universal', filename: 'launch-logo@3x.png', scale: '3x' },
      ],
      info: { author: 'xcode', version: 1 },
    },
    null,
    2,
  ),
);

const [r, g, bl] = BG.map((c) => (c / 255).toFixed(4));
